CREATE VIEW v_lawyer_search AS
SELECT lp.user_id AS lawyer_id, u.full_name, u.avatar_url, lp.honorific, lp.headline,
       lp.bar_council_no, lp.years_experience, lp.avg_rating, lp.review_count,
       lp.consultation_fee, lp.session_minutes, lp.formats, lp.sos_available, lp.district,
       c.name AS primary_court,
       COALESCE(pa.areas, '{}') AS practice_areas,
       ns.next_slot
FROM lawyer_profiles lp
JOIN users u ON u.id = lp.user_id AND u.status = 'active' AND u.deleted_at IS NULL
LEFT JOIN courts c ON c.id = lp.primary_court_id
LEFT JOIN LATERAL (
  SELECT array_agg(p.name_en ORDER BY p.name_en) AS areas
  FROM lawyer_practice_areas x JOIN practice_areas p ON p.id = x.practice_area_id
  WHERE x.lawyer_id = lp.user_id) pa ON true
LEFT JOIN LATERAL (
  SELECT min(s.starts_at) AS next_slot FROM lawyer_availability_slots s
  WHERE s.lawyer_id = lp.user_id AND s.starts_at > now() AND NOT s.is_booked) ns ON true
WHERE lp.verification_status = 'approved';

