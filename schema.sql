-- 11.1 generic updated_at
CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

DO $$
DECLARE t text;
BEGIN
  FOR t IN
    SELECT c.table_name FROM information_schema.columns c
    WHERE c.table_schema = 'lawaid' AND c.column_name = 'updated_at'
  LOOP
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated BEFORE UPDATE ON lawaid.%1$I
                    FOR EACH ROW EXECUTE FUNCTION lawaid.set_updated_at()', t);
  END LOOP;
END $$;

-- 11.2 only approved lawyers can be booked (FR-3)
CREATE FUNCTION chk_lawyer_approved() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v verification_status;
BEGIN
  SELECT verification_status INTO v FROM lawyer_profiles WHERE user_id = NEW.lawyer_id;
  IF v IS DISTINCT FROM 'approved' THEN
    RAISE EXCEPTION 'Lawyer % is not verified and cannot be booked', NEW.lawyer_id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_appt_lawyer_approved BEFORE INSERT ON appointments
  FOR EACH ROW EXECUTE FUNCTION chk_lawyer_approved();

-- 11.3 appointment status history (FR-37). App may SET LOCAL lawaid.user_id.
CREATE FUNCTION log_appointment_status() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE actor uuid := NULLIF(current_setting('lawaid.user_id', true), '')::uuid;
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO appointment_status_history(appointment_id, from_status, to_status, changed_by)
    VALUES (NEW.id, NULL, NEW.status, actor);
  ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO appointment_status_history(appointment_id, from_status, to_status, changed_by)
    VALUES (NEW.id, OLD.status, NEW.status, actor);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_appt_status_log AFTER INSERT OR UPDATE OF status ON appointments
  FOR EACH ROW EXECUTE FUNCTION log_appointment_status();

-- 11.4 keep lawyer_availability_slots.is_booked in sync
CREATE FUNCTION sync_slot_booking() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE sid uuid;
BEGIN
  FOREACH sid IN ARRAY ARRAY[NEW.slot_id, CASE WHEN TG_OP = 'UPDATE' THEN OLD.slot_id END] LOOP
    CONTINUE WHEN sid IS NULL;
    UPDATE lawyer_availability_slots s
       SET is_booked = EXISTS (SELECT 1 FROM appointments a
                               WHERE a.slot_id = sid
                                 AND a.status NOT IN ('cancelled','declined','expired','refunded'))
     WHERE s.id = sid;
  END LOOP;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_appt_slot_sync AFTER INSERT OR UPDATE OF slot_id, status ON appointments
  FOR EACH ROW EXECUTE FUNCTION sync_slot_booking();

-- 11.5 reviews allowed only after a completed consultation by that client (FR-30)
CREATE FUNCTION chk_review_allowed() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE a appointments%ROWTYPE;
BEGIN
  SELECT * INTO a FROM appointments WHERE id = NEW.appointment_id;
  IF a.client_id <> NEW.client_id OR a.lawyer_id <> NEW.lawyer_id THEN
    RAISE EXCEPTION 'Review parties do not match the appointment' USING ERRCODE = 'check_violation';
  END IF;
  IF a.status NOT IN ('completed', 'payment_released', 'reviewed', 'closed') THEN
    RAISE EXCEPTION 'Appointment % is not completed; review not allowed', a.id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_review_allowed BEFORE INSERT ON reviews
  FOR EACH ROW EXECUTE FUNCTION chk_review_allowed();

-- 11.6 maintain lawyer average rating + count (FR-31)
CREATE FUNCTION refresh_lawyer_rating() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE lid uuid := COALESCE(NEW.lawyer_id, OLD.lawyer_id);
BEGIN
  UPDATE lawyer_profiles lp
     SET avg_rating   = COALESCE((SELECT round(avg(rating)::numeric, 2) FROM reviews WHERE lawyer_id = lid), 0),
         review_count = (SELECT count(*) FROM reviews WHERE lawyer_id = lid)
   WHERE lp.user_id = lid;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_review_rating AFTER INSERT OR UPDATE OR DELETE ON reviews
  FOR EACH ROW EXECUTE FUNCTION refresh_lawyer_rating();

-- 11.7 keep cases.next_hearing_at in sync with case_hearings
CREATE FUNCTION refresh_next_hearing() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE cid uuid := COALESCE(NEW.case_id, OLD.case_id);
BEGIN
  UPDATE cases SET next_hearing_at =
    (SELECT min(hearing_at) FROM case_hearings
      WHERE case_id = cid AND status = 'scheduled' AND hearing_at >= now())
  WHERE id = cid;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_hearing_next AFTER INSERT OR UPDATE OR DELETE ON case_hearings
  FOR EACH ROW EXECUTE FUNCTION refresh_next_hearing();

-- 11.8 bump conversation.last_message_at
CREATE FUNCTION touch_conversation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE conversations SET last_message_at = NEW.sent_at WHERE id = NEW.conversation_id;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_message_touch AFTER INSERT ON messages
  FOR EACH ROW EXECUTE FUNCTION touch_conversation();

-- 11.9 expire unpaid holds - call from a cron / pg_cron job every minute (use case alt. scenario)
CREATE FUNCTION expire_unpaid_holds() RETURNS integer LANGUAGE sql AS $$
  WITH x AS (
    UPDATE appointments SET status = 'expired'
     WHERE status IN ('slot_reserved', 'payment_pending') AND hold_expires_at < now()
    RETURNING 1)
  SELECT count(*)::int FROM x;
$$;

-- 11.10 release escrow after client confirmation (FR-22) - single atomic call
CREATE FUNCTION release_escrow(p_appointment uuid) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  UPDATE payments SET escrow = 'released', escrow_released_at = now()
   WHERE appointment_id = p_appointment AND status = 'succeeded' AND escrow = 'held';
  IF NOT FOUND THEN
    RAISE EXCEPTION 'No held escrow for appointment %', p_appointment;
  END IF;
  UPDATE appointments SET status = 'payment_released'
   WHERE id = p_appointment AND status IN ('completed', 'disputed');
END $$;

