BEGIN;

CREATE EXTENSION IF NOT EXISTS citext;      -- case-insensitive e-mail
CREATE EXTENSION IF NOT EXISTS pgcrypto;    -- gen_random_bytes(), crypt()
CREATE EXTENSION IF NOT EXISTS btree_gist;  -- no-overlap constraint on lawyer slots
CREATE EXTENSION IF NOT EXISTS pg_trgm;     -- fuzzy lawyer / case search

DROP SCHEMA IF EXISTS lawaid CASCADE;
CREATE SCHEMA lawaid;
SET search_path = lawaid, public;

-- ---------------------------------------------------------------------
-- 1. ENUM TYPES
-- ---------------------------------------------------------------------
CREATE TYPE user_role            AS ENUM ('client', 'lawyer', 'admin');
CREATE TYPE account_status       AS ENUM ('invited', 'pending_verification', 'active', 'suspended', 'deactivated');
CREATE TYPE language_code        AS ENUM ('bn', 'en');
CREATE TYPE gender_type          AS ENUM ('male', 'female', 'other', 'undisclosed');
CREATE TYPE verification_status  AS ENUM ('pending', 'approved', 'rejected');
CREATE TYPE verification_doc     AS ENUM ('nid', 'bar_certificate');
CREATE TYPE consultation_format  AS ENUM ('video', 'audio', 'chat', 'in_person');

-- Mirrors the State Diagram (section 7.7)
CREATE TYPE appointment_status AS ENUM (
  'slot_reserved', 'payment_pending', 'awaiting_lawyer', 'rescheduled',
  'confirmed', 'in_progress', 'completed', 'disputed',
  'payment_released', 'reviewed', 'closed',
  'cancelled', 'declined', 'expired', 'refunded'
);

CREATE TYPE payment_method   AS ENUM ('sslcommerz', 'bkash', 'nagad');
CREATE TYPE payment_status   AS ENUM ('initiated', 'pending', 'succeeded', 'failed', 'refunded');
CREATE TYPE escrow_status    AS ENUM ('none', 'held', 'released', 'refunded', 'disputed');
CREATE TYPE dispute_status   AS ENUM ('open', 'under_review', 'resolved_for_lawyer', 'resolved_for_client', 'withdrawn');

CREATE TYPE case_status      AS ENUM ('open', 'in_progress', 'pending_review', 'disposed', 'closed');
CREATE TYPE case_urgency     AS ENUM ('regular', 'urgent', 'vacation_bench');
CREATE TYPE hearing_status   AS ENUM ('scheduled', 'held', 'adjourned', 'cancelled');
CREATE TYPE document_status  AS ENUM ('pending_review', 'verified', 'action_required', 'rejected');
CREATE TYPE recipient_type   AS ENUM ('client', 'lawyer', 'court_registry');
CREATE TYPE request_status   AS ENUM ('sent', 'partially_fulfilled', 'fulfilled', 'cancelled');
CREATE TYPE task_priority    AS ENUM ('urgent', 'medium', 'normal');
CREATE TYPE task_status      AS ENUM ('open', 'done', 'cancelled');
CREATE TYPE event_type       AS ENUM ('court_hearing', 'chamber_review', 'virtual_review', 'filing_deadline');

CREATE TYPE message_type     AS ENUM ('text', 'file', 'system');
CREATE TYPE ai_role          AS ENUM ('user', 'assistant', 'system');
CREATE TYPE sos_status       AS ENUM ('requested', 'matched', 'accepted', 'cancelled', 'expired', 'completed');
CREATE TYPE report_status    AS ENUM ('submitted', 'under_review', 'action_taken', 'dismissed');
CREATE TYPE notif_channel    AS ENUM ('in_app', 'push', 'sms', 'whatsapp', 'email');
CREATE TYPE notif_status     AS ENUM ('queued', 'sent', 'failed', 'read');
CREATE TYPE deletion_status  AS ENUM ('requested', 'processing', 'completed', 'rejected');

-- ---------------------------------------------------------------------
-- 2. REFERENCE / LOOKUP TABLES
-- ---------------------------------------------------------------------
CREATE TABLE courts (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      text NOT NULL UNIQUE,
  court_type text NOT NULL,                 -- supreme_court | district | tribunal | family | special
  district  text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE practice_areas (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug     text NOT NULL UNIQUE,
  name_en  text NOT NULL,
  name_bn  text NOT NULL
);

-- ---------------------------------------------------------------------
-- 3. USERS & PROFILES   (FR-1 .. FR-5, FR-34)
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id                  uuid PRIMARY KEY DEFAULT uuidv7(),
  role                user_role      NOT NULL,
  full_name           text           NOT NULL,
  email               citext         NOT NULL UNIQUE,
  phone               text           UNIQUE CHECK (phone ~ '^\+8801[3-9][0-9]{8}$'),
  password_hash       text           NOT NULL,
  preferred_language  language_code  NOT NULL DEFAULT 'bn',
  status              account_status NOT NULL DEFAULT 'active',
  avatar_url          text,
  two_factor_enabled  boolean        NOT NULL DEFAULT false,
  email_verified_at   timestamptz,
  phone_verified_at   timestamptz,
  last_login_at       timestamptz,
  suspended_reason    text,
  suspended_by        uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at          timestamptz    NOT NULL DEFAULT now(),
  updated_at          timestamptz    NOT NULL DEFAULT now(),
  deleted_at          timestamptz,                         -- soft delete (NFR-8)
  UNIQUE (id, role)                                         -- lets profile tables pin the role
);
CREATE INDEX idx_users_role_status ON users (role, status) WHERE deleted_at IS NULL;
CREATE INDEX idx_users_name_trgm   ON users USING gin (full_name gin_trgm_ops);

CREATE TABLE client_profiles (
  user_id        uuid PRIMARY KEY,
  role           user_role NOT NULL DEFAULT 'client' CHECK (role = 'client'),
  gender         gender_type NOT NULL DEFAULT 'undisclosed',
  date_of_birth  date,
  organization_name text,                  -- corporate litigants, e.g. "Metro Housing Ltd."
  division       text,
  district       text,
  address        text,
  created_by_lawyer_id uuid,               -- set when a lawyer registers a litigant ("Register New Litigant")
  FOREIGN KEY (user_id, role) REFERENCES users (id, role) ON DELETE CASCADE
);

CREATE TABLE lawyer_profiles (
  user_id             uuid PRIMARY KEY,
  role                user_role NOT NULL DEFAULT 'lawyer' CHECK (role = 'lawyer'),
  honorific           text,                                 -- Adv. / Barrister
  headline            text,                                 -- "Senior Advocate", "Advocate"
  bar_council_no      text NOT NULL UNIQUE,                 -- Sanad / Bar ID e.g. SC-7841
  bar_association     text,                                 -- SCBA, Dhaka Bar ...
  primary_court_id    integer REFERENCES courts(id),
  chamber_address     text,
  district            text,
  latitude            numeric(9,6),
  longitude           numeric(9,6),
  years_experience    smallint NOT NULL DEFAULT 0 CHECK (years_experience >= 0),
  bio                 text,
  consultation_fee    numeric(10,2) NOT NULL DEFAULT 0 CHECK (consultation_fee >= 0),
  session_minutes     smallint NOT NULL DEFAULT 30 CHECK (session_minutes BETWEEN 10 AND 240),
  formats             consultation_format[] NOT NULL DEFAULT '{video,audio,chat}',
  offers_free_session boolean NOT NULL DEFAULT false,       -- FR-10 free or paid booking
  sos_available       boolean NOT NULL DEFAULT false,       -- FR-16 emergency finder
  verification_status verification_status NOT NULL DEFAULT 'pending',
  verified_at         timestamptz,
  verified_by         uuid REFERENCES users(id) ON DELETE SET NULL,
  avg_rating          numeric(3,2) NOT NULL DEFAULT 0 CHECK (avg_rating BETWEEN 0 AND 5),
  review_count        integer NOT NULL DEFAULT 0,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (user_id, role) REFERENCES users (id, role) ON DELETE CASCADE
);
CREATE INDEX idx_lawyer_verified    ON lawyer_profiles (verification_status);
CREATE INDEX idx_lawyer_search      ON lawyer_profiles (district, avg_rating DESC, consultation_fee)
  WHERE verification_status = 'approved';
CREATE INDEX idx_lawyer_sos         ON lawyer_profiles (sos_available) WHERE sos_available AND verification_status = 'approved';

ALTER TABLE client_profiles
  ADD CONSTRAINT fk_client_created_by_lawyer
  FOREIGN KEY (created_by_lawyer_id) REFERENCES lawyer_profiles(user_id) ON DELETE SET NULL;

CREATE TABLE lawyer_practice_areas (
  lawyer_id        uuid    NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE CASCADE,
  practice_area_id integer NOT NULL REFERENCES practice_areas(id) ON DELETE RESTRICT,
  PRIMARY KEY (lawyer_id, practice_area_id)
);
CREATE INDEX idx_lpa_area ON lawyer_practice_areas (practice_area_id);

-- NID + Bar Council certificate  (FR-2, FR-3, FR-38, NFR-4)
-- file_url must point to an encrypted, admin-only bucket.
CREATE TABLE lawyer_verification_documents (
  id               uuid PRIMARY KEY DEFAULT uuidv7(),
  lawyer_id        uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE CASCADE,
  doc_type         verification_doc NOT NULL,
  file_url         text NOT NULL,
  status           verification_status NOT NULL DEFAULT 'pending',
  rejection_reason text,
  submitted_at     timestamptz NOT NULL DEFAULT now(),
  reviewed_by      uuid REFERENCES users(id) ON DELETE SET NULL,
  reviewed_at      timestamptz,
  CHECK (status <> 'rejected' OR rejection_reason IS NOT NULL)
);
CREATE INDEX idx_lvd_queue ON lawyer_verification_documents (status, submitted_at) WHERE status = 'pending';

-- Auth support (FR-4, FR-5, NFR-3)
CREATE TABLE refresh_tokens (
  id          uuid PRIMARY KEY DEFAULT uuidv7(),
  user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash  text NOT NULL UNIQUE,
  user_agent  text,
  ip_address  inet,
  expires_at  timestamptz NOT NULL,
  revoked_at  timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_refresh_user ON refresh_tokens (user_id) WHERE revoked_at IS NULL;

CREATE TABLE password_reset_tokens (
  id          uuid PRIMARY KEY DEFAULT uuidv7(),
  user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash  text NOT NULL UNIQUE,
  expires_at  timestamptz NOT NULL,
  used_at     timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE data_deletion_requests (               -- NFR-8
  id           uuid PRIMARY KEY DEFAULT uuidv7(),
  user_id      uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status       deletion_status NOT NULL DEFAULT 'requested',
  reason       text,
  requested_at timestamptz NOT NULL DEFAULT now(),
  processed_by uuid REFERENCES users(id) ON DELETE SET NULL,
  processed_at timestamptz
);

-- lawyer <-> client relationship ("My Clients" page)
CREATE TABLE lawyer_clients (
  lawyer_id  uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE CASCADE,
  client_id  uuid NOT NULL REFERENCES client_profiles(user_id) ON DELETE CASCADE,
  since      date NOT NULL DEFAULT current_date,
  notes      text,
  PRIMARY KEY (lawyer_id, client_id)
);
CREATE INDEX idx_lawyer_clients_client ON lawyer_clients (client_id);

-- ---------------------------------------------------------------------
-- 4. AVAILABILITY, APPOINTMENTS, SESSIONS   (FR-10 .. FR-16)
-- ---------------------------------------------------------------------
CREATE TABLE lawyer_availability_slots (
  id         uuid PRIMARY KEY DEFAULT uuidv7(),
  lawyer_id  uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE CASCADE,
  starts_at  timestamptz NOT NULL,
  ends_at    timestamptz NOT NULL,
  formats    consultation_format[] NOT NULL DEFAULT '{video,audio,chat}',
  is_booked  boolean NOT NULL DEFAULT false,        -- maintained by trigger on appointments
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (ends_at > starts_at),
  EXCLUDE USING gist (lawyer_id WITH =, tstzrange(starts_at, ends_at) WITH &&)   -- a lawyer can't double-publish time
);
CREATE INDEX idx_slots_open ON lawyer_availability_slots (lawyer_id, starts_at) WHERE NOT is_booked;

-- Case is created before appointments reference it
CREATE TABLE cases (
  id              uuid PRIMARY KEY DEFAULT uuidv7(),
  case_no         text NOT NULL UNIQUE,                     -- e.g. CP-2024-0491
  title           text NOT NULL,                            -- "Metro Housing Ltd. vs. Land Ministry & Ors."
  category        text NOT NULL,                            -- Writ Petition, Civil Suit, Arbitration ...
  nature_tag      text,                                     -- "WRIT & LAND DISPUTE"
  practice_area_id integer REFERENCES practice_areas(id),
  court_id        integer REFERENCES courts(id),
  bench           text,                                     -- "Hon. Justice M. A. Rahman (Bench 07)"
  jurisdiction    text,
  lawyer_id       uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE RESTRICT,
  client_id       uuid NOT NULL REFERENCES client_profiles(user_id) ON DELETE RESTRICT,
  opposing_party  text,
  narrative       text,
  status          case_status  NOT NULL DEFAULT 'open',     -- FR-20
  urgency         case_urgency NOT NULL DEFAULT 'regular',
  filed_at        date,
  next_hearing_at timestamptz,                              -- denormalised from case_hearings
  disposed_at     date,
  final_judgment  text,
  stamp_fee_bdt   numeric(10,2),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_cases_lawyer_status ON cases (lawyer_id, status);
CREATE INDEX idx_cases_client        ON cases (client_id, status);
CREATE INDEX idx_cases_title_trgm    ON cases USING gin (title gin_trgm_ops);

CREATE TABLE appointments (
  id                 uuid PRIMARY KEY DEFAULT uuidv7(),
  client_id          uuid NOT NULL REFERENCES client_profiles(user_id) ON DELETE RESTRICT,
  lawyer_id          uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE RESTRICT,
  slot_id            uuid REFERENCES lawyer_availability_slots(id) ON DELETE SET NULL,
  proposed_slot_id   uuid REFERENCES lawyer_availability_slots(id) ON DELETE SET NULL,  -- lawyer's reschedule offer
  case_id            uuid REFERENCES cases(id) ON DELETE SET NULL,
  practice_area_id   integer REFERENCES practice_areas(id),
  format             consultation_format NOT NULL,
  status             appointment_status  NOT NULL DEFAULT 'slot_reserved',
  scheduled_start    timestamptz NOT NULL,
  scheduled_end      timestamptz NOT NULL,
  issue_summary      text,
  fee_amount         numeric(10,2) NOT NULL DEFAULT 0 CHECK (fee_amount >= 0),
  is_free            boolean GENERATED ALWAYS AS (fee_amount = 0) STORED,
  is_sos             boolean NOT NULL DEFAULT false,
  ai_recommended     boolean NOT NULL DEFAULT false,
  hold_expires_at    timestamptz,                           -- slot hold while payment is pending
  cancelled_by       uuid REFERENCES users(id) ON DELETE SET NULL,
  cancel_reason      text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CHECK (scheduled_end > scheduled_start)
);
CREATE INDEX idx_appt_client ON appointments (client_id, scheduled_start DESC);
CREATE INDEX idx_appt_lawyer ON appointments (lawyer_id, scheduled_start DESC);
CREATE INDEX idx_appt_status ON appointments (status);
CREATE INDEX idx_appt_hold   ON appointments (hold_expires_at) WHERE status IN ('slot_reserved', 'payment_pending');
-- one live appointment per slot (prevents double-booking even under concurrency)
CREATE UNIQUE INDEX uq_appt_active_slot ON appointments (slot_id)
  WHERE slot_id IS NOT NULL AND status NOT IN ('cancelled', 'declined', 'expired', 'refunded');

CREATE TABLE appointment_status_history (             -- FR-37 audit / dispute evidence
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  appointment_id uuid NOT NULL REFERENCES appointments(id) ON DELETE CASCADE,
  from_status    appointment_status,
  to_status      appointment_status NOT NULL,
  changed_by     uuid REFERENCES users(id) ON DELETE SET NULL,
  note           text,
  changed_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_ash_appt ON appointment_status_history (appointment_id, changed_at);

CREATE TABLE consultation_sessions (                  -- live video / audio / chat room (FR-14)
  id             uuid PRIMARY KEY DEFAULT uuidv7(),
  appointment_id uuid NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE CASCADE,
  room_id        text NOT NULL UNIQUE DEFAULT encode(gen_random_bytes(12), 'hex'),
  started_at     timestamptz,
  ended_at       timestamptz,
  duration_sec   integer GENERATED ALWAYS AS (EXTRACT(EPOCH FROM (ended_at - started_at))::integer) STORED,
  lawyer_notes   text,
  CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE sos_requests (                           -- FR-16
  id            uuid PRIMARY KEY DEFAULT uuidv7(),
  client_id     uuid NOT NULL REFERENCES client_profiles(user_id) ON DELETE CASCADE,
  description   text NOT NULL,
  latitude      numeric(9,6),
  longitude     numeric(9,6),
  status        sos_status NOT NULL DEFAULT 'requested',
  lawyer_id     uuid REFERENCES lawyer_profiles(user_id) ON DELETE SET NULL,
  appointment_id uuid REFERENCES appointments(id) ON DELETE SET NULL,
  requested_at  timestamptz NOT NULL DEFAULT now(),
  accepted_at   timestamptz
);
CREATE INDEX idx_sos_open ON sos_requests (requested_at) WHERE status IN ('requested', 'matched');

-- ---------------------------------------------------------------------
-- 5. PAYMENTS, ESCROW, RECEIPTS   (FR-21 .. FR-25, NFR-5, NFR-17)
--    No card / wallet numbers are stored - only gateway references.
-- ---------------------------------------------------------------------
CREATE SEQUENCE receipt_seq START 1;

CREATE TABLE payments (
  id               uuid PRIMARY KEY DEFAULT uuidv7(),
  appointment_id   uuid NOT NULL REFERENCES appointments(id) ON DELETE RESTRICT,
  client_id        uuid NOT NULL REFERENCES client_profiles(user_id) ON DELETE RESTRICT,
  lawyer_id        uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE RESTRICT,
  amount           numeric(12,2) NOT NULL CHECK (amount > 0),
  platform_fee     numeric(12,2) NOT NULL DEFAULT 0 CHECK (platform_fee >= 0),
  lawyer_payout    numeric(12,2) GENERATED ALWAYS AS (amount - platform_fee) STORED,
  currency         char(3) NOT NULL DEFAULT 'BDT',
  method           payment_method NOT NULL,
  gateway_txn_id   text,
  gateway_payload  jsonb,                               -- sanitized gateway response
  status           payment_status NOT NULL DEFAULT 'initiated',
  escrow           escrow_status  NOT NULL DEFAULT 'none',
  paid_at          timestamptz,
  escrow_released_at timestamptz,
  refunded_at      timestamptz,
  failure_reason   text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CHECK (platform_fee <= amount),
  CHECK (escrow = 'none' OR status IN ('succeeded', 'refunded'))
);
CREATE UNIQUE INDEX uq_payment_gateway_txn ON payments (method, gateway_txn_id) WHERE gateway_txn_id IS NOT NULL;
-- never two successful charges for one booking (NFR-17)
CREATE UNIQUE INDEX uq_payment_one_success ON payments (appointment_id) WHERE status = 'succeeded';
CREATE INDEX idx_payments_client ON payments (client_id, created_at DESC);
CREATE INDEX idx_payments_lawyer ON payments (lawyer_id, created_at DESC);
CREATE INDEX idx_payments_escrow ON payments (escrow) WHERE escrow IN ('held', 'disputed');

CREATE TABLE receipts (                               -- FR-23
  id          uuid PRIMARY KEY DEFAULT uuidv7(),
  payment_id  uuid NOT NULL UNIQUE REFERENCES payments(id) ON DELETE CASCADE,
  receipt_no  text NOT NULL UNIQUE
              DEFAULT ('LA-' || to_char(now(), 'YYYYMMDD') || '-' || lpad(nextval('receipt_seq')::text, 6, '0')),
  qr_token    text NOT NULL UNIQUE DEFAULT encode(gen_random_bytes(16), 'hex'),  -- encoded into QR; verify URL = /verify/<qr_token>
  issued_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE payment_disputes (                       -- FR-25
  id           uuid PRIMARY KEY DEFAULT uuidv7(),
  payment_id   uuid NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
  raised_by    uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  reason       text NOT NULL,
  status       dispute_status NOT NULL DEFAULT 'open',
  resolution   text,
  resolved_by  uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  resolved_at  timestamptz
);
CREATE UNIQUE INDEX uq_dispute_open ON payment_disputes (payment_id) WHERE status IN ('open', 'under_review');

-- ---------------------------------------------------------------------
-- 6. CASE MANAGEMENT   (FR-17 .. FR-20)
-- ---------------------------------------------------------------------
CREATE TABLE case_hearings (
  id           uuid PRIMARY KEY DEFAULT uuidv7(),
  case_id      uuid NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  hearing_at   timestamptz NOT NULL,
  bench        text,
  courtroom    text,
  cause_list_item integer,
  purpose      text,                                    -- "Hearing on Injunction Application"
  status       hearing_status NOT NULL DEFAULT 'scheduled',
  outcome      text,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_hearings_case ON case_hearings (case_id, hearing_at);
CREATE INDEX idx_hearings_upcoming ON case_hearings (hearing_at) WHERE status = 'scheduled';

CREATE TABLE case_team_members (
  case_id   uuid NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  user_id   uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  team_role text NOT NULL,                              -- Lead Senior Counsel, Junior Associate, Client ...
  PRIMARY KEY (case_id, user_id)
);

CREATE TABLE case_updates (                           -- timeline visible to client (FR-20)
  id         uuid PRIMARY KEY DEFAULT uuidv7(),
  case_id    uuid NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  author_id  uuid REFERENCES users(id) ON DELETE SET NULL,
  message    text NOT NULL,
  is_client_visible boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_case_updates ON case_updates (case_id, created_at DESC);

CREATE TABLE case_documents (                         -- FR-19, NFR-1
  id            uuid PRIMARY KEY DEFAULT uuidv7(),
  case_id       uuid REFERENCES cases(id) ON DELETE CASCADE,
  uploaded_by   uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  title         text NOT NULL,
  category      text NOT NULL,                          -- Plaint, Written Statement, Affidavit, Exhibit ...
  filed_by_party text,
  file_url      text NOT NULL,
  mime_type     text,
  size_bytes    bigint CHECK (size_bytes >= 0),
  page_count    integer,
  status        document_status NOT NULL DEFAULT 'pending_review',
  verified_by   uuid REFERENCES users(id) ON DELETE SET NULL,
  verified_at   timestamptz,
  review_note   text,
  is_encrypted  boolean NOT NULL DEFAULT true,
  uploaded_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_docs_case ON case_documents (case_id, uploaded_at DESC);
CREATE INDEX idx_docs_review ON case_documents (status) WHERE status IN ('pending_review', 'action_required');

CREATE TABLE document_requests (                      -- lawyer "Request Documents" modal
  id             uuid PRIMARY KEY DEFAULT uuidv7(),
  requested_by   uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE CASCADE,
  recipient_type recipient_type NOT NULL,
  recipient_user_id uuid REFERENCES users(id) ON DELETE SET NULL,
  recipient_name text NOT NULL,
  case_id        uuid REFERENCES cases(id) ON DELETE SET NULL,
  status         request_status NOT NULL DEFAULT 'sent',
  due_at         timestamptz,
  channels       notif_channel[] NOT NULL DEFAULT '{sms,whatsapp}',
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE document_request_items (
  id          uuid PRIMARY KEY DEFAULT uuidv7(),
  request_id  uuid NOT NULL REFERENCES document_requests(id) ON DELETE CASCADE,
  label       text NOT NULL,
  priority    text NOT NULL DEFAULT 'STANDARD' CHECK (priority IN ('URGENT', 'MANDATORY', 'STANDARD')),
  fulfilled_document_id uuid REFERENCES case_documents(id) ON DELETE SET NULL
);

CREATE TABLE tasks (                                  -- "Tasks & Schedule" page
  id          uuid PRIMARY KEY DEFAULT uuidv7(),
  lawyer_id   uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE CASCADE,
  assignee_id uuid REFERENCES users(id) ON DELETE SET NULL,
  case_id     uuid REFERENCES cases(id) ON DELETE SET NULL,
  title       text NOT NULL,
  priority    task_priority NOT NULL DEFAULT 'normal',
  status      task_status   NOT NULL DEFAULT 'open',
  due_at      timestamptz,
  completed_at timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_tasks_lawyer ON tasks (lawyer_id, status, due_at);

CREATE TABLE calendar_events (
  id            uuid PRIMARY KEY DEFAULT uuidv7(),
  lawyer_id     uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE CASCADE,
  event_type    event_type NOT NULL,
  title         text NOT NULL,
  location      text,
  case_id       uuid REFERENCES cases(id) ON DELETE SET NULL,
  hearing_id    uuid REFERENCES case_hearings(id) ON DELETE SET NULL,
  appointment_id uuid REFERENCES appointments(id) ON DELETE SET NULL,
  starts_at     timestamptz NOT NULL,
  ends_at       timestamptz,
  reminder_minutes_before integer DEFAULT 30,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CHECK (ends_at IS NULL OR ends_at >= starts_at)
);
CREATE INDEX idx_cal_lawyer ON calendar_events (lawyer_id, starts_at);

-- ---------------------------------------------------------------------
-- 7. MESSAGING
-- ---------------------------------------------------------------------
CREATE TABLE conversations (
  id          uuid PRIMARY KEY DEFAULT uuidv7(),
  client_id   uuid NOT NULL REFERENCES client_profiles(user_id) ON DELETE CASCADE,
  lawyer_id   uuid NOT NULL REFERENCES lawyer_profiles(user_id) ON DELETE CASCADE,
  case_id     uuid REFERENCES cases(id) ON DELETE SET NULL,
  appointment_id uuid REFERENCES appointments(id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
