  (SELECT count(*) FROM appointments a WHERE a.lawyer_id = lp.user_id
     AND a.scheduled_start::date = current_date AND a.status IN ('confirmed','in_progress'))         AS todays_sessions,
  (SELECT count(*) FROM appointments a WHERE a.lawyer_id = lp.user_id AND a.status = 'awaiting_lawyer') AS pending_requests,
