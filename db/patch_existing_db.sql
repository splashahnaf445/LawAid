--   psql -h localhost -p 5433 -U postgres -d Lawaid -f db/patch_existing_db.sql
-- New databases built from the updated schema.sql do not need this.
SET search_path = lawaid, public;
BEGIN;

ALTER TABLE lawyer_profiles
  ADD COLUMN IF NOT EXISTS rejection_reason text,
  ADD COLUMN IF NOT EXISTS specialization  text NOT NULL DEFAULT 'Civil Litigation, Property Law';

ALTER TABLE lawyer_verification_documents
  ADD COLUMN IF NOT EXISTS original_filename text   NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS mime_type         text   NOT NULL DEFAULT 'application/pdf',
  ADD COLUMN IF NOT EXISTS file_size_bytes   bigint NOT NULL DEFAULT 0;

ALTER TABLE client_profiles
  ADD COLUMN IF NOT EXISTS nid_number        text,
  ADD COLUMN IF NOT EXISTS emergency_contact text,
  ADD COLUMN IF NOT EXISTS created_at        timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS updated_at        timestamptz NOT NULL DEFAULT now();

-- lawyer_practice_areas: composite PK -> single id column + unique pair
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_schema = 'lawaid' AND table_name = 'lawyer_practice_areas' AND column_name = 'id') THEN
    ALTER TABLE lawyer_practice_areas DROP CONSTRAINT lawyer_practice_areas_pkey;
    ALTER TABLE lawyer_practice_areas ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
    ALTER TABLE lawyer_practice_areas ADD CONSTRAINT lawyer_practice_areas_lawyer_area_key
      UNIQUE (lawyer_id, practice_area_id);
  END IF;
END $$;

-- password hashes: 'bcrypt$2a$..' (broken) or '$2a$..' (raw) -> 'bcrypt$$2a$..'
UPDATE users SET password_hash = 'bcrypt$' || substr(password_hash, 7) WHERE password_hash LIKE 'bcrypt$2%';
UPDATE users SET password_hash = 'bcrypt$' || password_hash            WHERE password_hash LIKE '$2%';

COMMIT;
